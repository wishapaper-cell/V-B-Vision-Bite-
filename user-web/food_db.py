def seed_food_library(db_conn):
    """只在食物库为空时插入预设数据"""
    existing = db_conn.execute("SELECT COUNT(*) FROM food_library").fetchone()[0]
    if existing > 0:
        return
    for name, cal, na, k, ca, mg, fe, cat in FOODS:
        db_conn.execute(
            "INSERT INTO food_library (name, calories_per_100g, "
            "sodium_mg, potassium_mg, calcium_mg, magnesium_mg, iron_mg, category) "
            "VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
            (name, cal, na, k, ca, mg, fe, cat),
        )
    db_conn.commit()
